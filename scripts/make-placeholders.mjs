import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

/**
 * Generates the placeholder images the project pages ship with.
 *
 * These are real PNGs in the site's own palette, not grey boxes and not
 * `alt`-text-in-a-div: a missing image should look like a designed empty slot,
 * not like the page failed to load. Each one carries its project code and a
 * short label so it is obvious at a glance which slot it is.
 *
 * ── Replacing one ─────────────────────────────────────────────────────────
 * Drop a real image over the file at the same path. Nothing else changes as
 * long as the aspect ratio matches; if it does not, update `width`/`height` on
 * that entry in src/content/projects.ts and the layout follows.
 *
 *   pnpm placeholders    regenerate all of them
 *
 * TERRA and Mantau deliberately have no image slots at all — the Project type
 * makes images impossible on a confidential project — so nothing here targets
 * them.
 */

const PLATFORM = "#1E2733";
const PLATFORM_2 = "#26313F";
const RULE = "#3A4656";
const INK_2 = "#A9B4C0";
const LINE_WORK = "#4C8DFF";

const W = 1600;
const H = 1000;

/** One entry per image slot declared in src/content/projects.ts. */
const SLOTS = [
  ["skillpath", "01", "Regional skill-gap dashboard"],
  ["skillpath", "02", "Provincial dataset merge"],
  ["praktikum-apap", "01", "Service layer"],
  ["praktikum-apap", "02", "Front end"],
  ["kosinduy", "01", "Store, web"],
  ["kosinduy", "02", "Flutter client"],
  ["football-news", "01", "Reader, web"],
  ["football-news", "02", "Flutter client"],
];

function svg(code, label) {
  // Diagonal hatching, so the slot reads as deliberately empty rather than as
  // a broken image, and a station badge so it belongs to the signage system.
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}">
  <defs>
    <pattern id="hatch" width="28" height="28" patternUnits="userSpaceOnUse" patternTransform="rotate(45)">
      <line x1="0" y1="0" x2="0" y2="28" stroke="${RULE}" stroke-width="6" opacity="0.5"/>
    </pattern>
  </defs>
  <rect width="${W}" height="${H}" fill="${PLATFORM_2}"/>
  <rect width="${W}" height="${H}" fill="url(#hatch)"/>
  <rect x="0" y="0" width="14" height="${H}" fill="${LINE_WORK}"/>
  <rect x="70" y="${H / 2 - 132}" width="640" height="264" fill="${PLATFORM}"/>
  <rect x="70" y="${H / 2 - 132}" width="640" height="6" fill="${LINE_WORK}"/>
  <text x="110" y="${H / 2 - 44}" font-family="Archivo, Arial, sans-serif" font-size="52" font-weight="700" fill="${LINE_WORK}" letter-spacing="2">${code}</text>
  <text x="110" y="${H / 2 + 22}" font-family="Archivo, Arial, sans-serif" font-size="38" fill="#F3F5F7">${label}</text>
  <text x="110" y="${H / 2 + 78}" font-family="Archivo, Arial, sans-serif" font-size="26" fill="${INK_2}">placeholder — drop a real image here</text>
</svg>`;
}

// fileURLToPath, not URL.pathname: the project lives under a path with a
// space in it, and pathname percent-encodes it into a directory that does
// not exist.
const root = fileURLToPath(
  new URL("../public/images/projects/", import.meta.url),
);

for (const [slug, index, label] of SLOTS) {
  const file = join(root, slug, `${index}.png`);
  await mkdir(dirname(file), { recursive: true });
  await sharp(Buffer.from(svg(`${slug}/${index}`, label)))
    .png({ compressionLevel: 9, palette: true })
    .toFile(file);
  console.log(`  ${file}`);
}

// A tiny, heavily blurred version of the same ground, inlined as the blur
// placeholder so nothing flashes white before an image paints.
const blur = await sharp({
  create: {
    width: 8,
    height: 5,
    channels: 3,
    background: PLATFORM_2,
  },
})
  .png()
  .toBuffer();

await writeFile(
  fileURLToPath(new URL("../src/content/placeholder-blur.ts", import.meta.url)),
  `/** Generated by scripts/make-placeholders.mjs. Do not edit by hand. */\nexport const PLACEHOLDER_BLUR =\n  "data:image/png;base64,${blur.toString("base64")}";\n`,
);

console.log(`\n${SLOTS.length} placeholders written, blur token regenerated.`);
